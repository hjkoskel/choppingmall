#!/usr/bin/env python3
"""Embed the subset TTFs as C byte arrays: python3 tools/embed_font.py > src/c2d/font_data.c"""
import sys
def arr(name, path):
    d = open(path, 'rb').read()
    out = [f"const unsigned char {name}[{len(d)}] = {{"]
    for i in range(0, len(d), 24):
        out.append("  " + ",".join(str(b) for b in d[i:i+24]) + ",")
    out.append("};")
    out.append(f"const unsigned int {name}_len = {len(d)};")
    return "\n".join(out)
print("/* font_data.c - GENERATED by tools/embed_font.py. DejaVu Sans / Sans Bold (Bitstream Vera licence), subset. */")
print(arr("font_regular_ttf", "assets/DejaVuSans-subset.ttf"))
print(arr("font_bold_ttf", "assets/DejaVuSans-Bold-subset.ttf"))
