/* gen_nes_tables.c - host tool: writes src/nes_tables.h, the constant tables the shared core keeps in RAM on the C64
 * but which must live in ROM on the NES (2 KB RAM): direction vectors, centre-line waypoints, walkability bitmap.
 * build: see nes/Makefile.  usage: gen_nes_tables > src/nes_tables.h */
#include <stdio.h>
#include <string.h>
#include "assets.h"
#include "core.h"
#include "tables_gen.h"
static Assets A;
#define PSPEED 17
static void arr16(const char *n, const int *v) {
  int i; printf("static const i8 %s[32] = {", n);
  for (i = 0; i < 32; i++) printf("%s%d,", i % 16 ? " " : "\n  ", v[i]);
  printf("\n};\n");
}
int main(void) {
  int i, v[32], w[32];
  game_init(1);
  assets_build(&A);
  printf("/* nes_tables.h - GENERATED by nes/tools/gen_nes_tables.c. Do not edit. */\n#ifndef NES_TABLES_H\n#define NES_TABLES_H\n#include \"types.h\"\n");
  for (i = 0; i < 32; i++) { v[i] = (i16)((PSPEED * COS32[i]) >> 7); w[i] = (i16)((PSPEED * SIN32[i]) >> 7); }
  arr16("pvx", v); arr16("pvy", w);
  for (i = 0; i < 32; i++) { v[i] = (i16)((97 * COS32[i]) >> 7); w[i] = (i16)((97 * SIN32[i]) >> 7); }
  arr16("b97x", v); arr16("b97y", w);
  for (i = 0; i < 32; i++) { v[i] = (i16)((86 * COS32[i]) >> 7); w[i] = (i16)((86 * SIN32[i]) >> 7); }
  arr16("b86x", v); arr16("b86y", w);
  for (i = 0; i < 32; i++) {
    i16 ux = COS32[i], uy = SIN32[i]; u16 m = mdot(ux, uy);
    v[i] = (i16)((ux * 72) / (i16)m); w[i] = (i16)((uy * 72) / (i16)m);
  }
  arr16("clx", v); arr16("cly", w);
  { static const int RSPD3[3] = {12, 13, 15}; int l;  /* robot velocity tables per level: normal, slowed, reverse (see start_level) */
    for (l = 0; l < 3; l++) {
      int n = RSPD3[l], sl = (n * 9) >> 4, rv = (n * 13) >> 4, k;
      for (i = 0; i < 32; i++) { v[i] = (i16)(((i16)n * COS32[i]) >> 7); w[i] = (i16)(((i16)n * SIN32[i]) >> 7); }
      printf("/* level %d */\n", l + 1); { char nm[8]; sprintf(nm, "RVX%d", l + 1); arr16(nm, v); sprintf(nm, "RVY%d", l + 1); arr16(nm, w); }
      for (i = 0; i < 32; i++) { v[i] = (i16)(((i16)sl * COS32[i]) >> 7); w[i] = (i16)(((i16)sl * SIN32[i]) >> 7); }
      { char nm[8]; sprintf(nm, "RSX%d", l + 1); arr16(nm, v); sprintf(nm, "RSY%d", l + 1); arr16(nm, w); }
      for (i = 0; i < 32; i++) { v[i] = (i16)(((i16)rv * COS32[i]) >> 7); w[i] = (i16)(((i16)rv * SIN32[i]) >> 7); }
      { char nm[8]; sprintf(nm, "RBX%d", l + 1); arr16(nm, v); sprintf(nm, "RBY%d", l + 1); arr16(nm, w); }
      (void)k;
    }
    printf("static const i8 *const RTAB[18] = {\n");
    for (i = 0; i < 3; i++) printf("  RVX%d, RVY%d, RSX%d, RSY%d, RBX%d, RBY%d,\n", i + 1, i + 1, i + 1, i + 1, i + 1, i + 1);
    printf("};\n");
  }
  { /* coverage grid: 1 bit per 8x8 cell (40 x 25) that is within reach of an obstacle, 5 bytes per row */
    static u8 grid[25][5]; int k, cx, cy;
    for (k = 0; k < NOB; k++)
      for (cy = (oby[k] - OBH - 6) >> 3; cy <= (oby[k] + OBH + 6) >> 3; cy++)
        for (cx = (obx[k] - OBH - 6) >> 3; cx <= (obx[k] + OBH + 6) >> 3; cx++) grid[cy][cx >> 3] |= (u8)(0x80 >> (cx & 7));
    printf("static const u8 NES_OBG[125] = {");
    for (i = 0; i < 125; i++) printf("%s%u,", i % 5 ? " " : "\n  ", grid[i / 5][i % 5]);
    printf("\n};\n");
  }
  printf("#ifndef NES_NO_WALKMAP\nstatic const u8 NES_WALK[%d] = {", 200 * 27);
  for (i = 0; i < 200 * 27; i++) printf("%s%u,", i % 27 ? " " : "\n  ", A.walk[i]);
  printf("\n};\n#endif\n#endif\n");
  return 0;
}
