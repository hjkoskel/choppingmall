#!/usr/bin/env python3
"""Generates src/tables_gen.h: direction vectors, SID note frequencies and the music, converted from
the original sequencer tables (../src/sound/music_data.c). usage: python3 tools/gen_tables.py > src/tables_gen.h"""
import math, re, sys, os
here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, '..', '..', 'src', 'sound', 'music_data.c')).read()
def table(name):
    body = re.search(r'const char \*const %s\[ML_BARS\] = \{(.*?)\};' % name, src, re.S).group(1)
    return re.findall(r'"([^"]*)"', body)
lead1, bass, drums = table('ml_lead1'), table('ml_bass'), table('ml_drums')
def midi(n):
    m = re.match(r'^([A-G])([#b]?)(\d)$', n)
    semi = {'C': 0, 'D': 2, 'E': 4, 'F': 5, 'G': 7, 'A': 9, 'B': 11}[m.group(1)]
    semi += {'#': 1, 'b': -1, '': 0}[m.group(2)]
    return 12 * (int(m.group(3)) + 1) + semi
def notes(bars):
    out = []
    for bar in bars:
        for tok in bar.split(' '):
            out.append(0 if tok == '-' else midi(tok.split('+')[0]))
    return out
def drum_flags(bars):
    out = []
    for bar in bars:
        for tok in bar.split(' '):
            out.append((1 if 'k' in tok else 0) | (2 if 's' in tok else 0) | (4 if 'h' in tok else 0) | (8 if 'c' in tok else 0))
    return out
def arr(ctype, name, vals, per=16):
    lines = [f'static const {ctype} {name}[{len(vals)}] = {{']
    for i in range(0, len(vals), per):
        lines.append('  ' + ', '.join(str(v) for v in vals[i:i + per]) + ',')
    lines.append('};')
    return '\n'.join(lines)
PAL = 985248.0
def sid(m): return round(440.0 * 2 ** ((m - 69) / 12) * 16777216 / PAL)
which = sys.argv[1] if len(sys.argv) > 1 else 'tables'
if which == 'tables':
    print('/* tables_gen.h - GENERATED by tools/gen_tables.py tables. Do not edit. */')
    print('#ifndef TABLES_GEN_H\n#define TABLES_GEN_H\n#include "types.h"')
    print('/* 32 directions, 11.25 degrees apart, clockwise from +x (screen y points down), Q7 */')
    print(arr('i8', 'COS32', [round(127 * math.cos(i * math.pi / 16)) for i in range(32)]))
    print(arr('i8', 'SIN32', [round(127 * math.sin(i * math.pi / 16)) for i in range(32)]))
    print('/* (222 * i) >> 8: 0.867 = cos 30 degrees, for the hexagon distance, as a table instead of a 6502 multiply */')
    print(arr('u8', 'T87', [(222 * i) >> 8 for i in range(251)], 20))
    print('/* atan thresholds for ang32: octant step k counts how many of the 4 tables have n >= T[d] (ratios 1/8, 5/16, 17/32, 13/16) */')
    for nm, (a, b) in (('ANG_T1', (1, 8)), ('ANG_T2', (5, 16)), ('ANG_T3', (17, 32)), ('ANG_T4', (13, 16))):
        print(arr('u8', nm, [min(255, -(-d * a // b)) for d in range(256)], 20))
    print('#endif')
else:
    print('/* music_gen.h - GENERATED by tools/gen_tables.py music. Do not edit. */')
    print('#ifndef MUSIC_GEN_H\n#define MUSIC_GEN_H\n#include "types.h"')
    print('/* SID frequency register value (PAL) for MIDI notes 0..95 */')
    print(arr('u16', 'SID_FREQ', [str(sid(m)) + 'u' for m in range(96)], 12))
    print('/* music: 96 eighth-note slots (12 bars x 8): MIDI note or 0; drums bit0 kick, 1 snare, 2 hat, 3 crash */')
    print(arr('u8', 'MUS_LEAD', notes(lead1), 24))
    print(arr('u8', 'MUS_BASS', notes(bass), 24))
    print(arr('u8', 'MUS_DRUM', drum_flags(drums), 24))
    print('#endif')
