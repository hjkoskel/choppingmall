#!/usr/bin/env python3
"""Generates src/jingle_gen.h: the win and lose stingers for the 3 SID voices, transcribed from jingleWin()/jingleLose() in the JavaScript game
(reference/index.html). usage: python3 tools/gen_jingles.py > src/jingle_gen.h
Each voice is a stream of 3-byte events: wait (frames, 0-255), note (MIDI; 0 = gate off, 254 = keep going, 255 = end of stream),
instrument (bit 7 = only change the pitch, do not retrigger). The player is snd_frame()/jingle_frame() in plat_c64.c."""
import re
SEMI = {'C': 0, 'D': 2, 'E': 4, 'F': 5, 'G': 7, 'A': 9, 'B': 11}
def m(n):
    g = re.match(r'^([A-G])([#b]?)(\d)$', n)
    return 12 * (int(g.group(3)) + 1) + SEMI[g.group(1)] + {'#': 1, 'b': -1, '': 0}[g.group(2)]
# instruments: wave, pulse width (hi byte), attack/decay, sustain/release
BRASS, STRINGS, PIANO, BASS, TIMP, ARP = range(6)
INST = [(0x40, 0x08, 0x08, 0xA8),   # brass: pulse, quick attack, sustained
        (0x20, 0x00, 0x59, 0x98),   # strings: saw, slower attack
        (0x10, 0x00, 0x0A, 0x30),   # piano: triangle, decaying
        (0x20, 0x00, 0x08, 0xC8),   # bass: saw
        (0x10, 0x00, 0x05, 0x00),   # timpani: triangle thump
        (0x40, 0x04, 0x03, 0x60)]   # arpeggio pluck: narrow pulse
class Piece:
    def __init__(self, bpm, beats):
        self.fpb = 60.0 / bpm * 50; self.end = round(beats * self.fpb + 40)  # + 0.8 s tail, as in the JS version
        self.v = [[], [], []]
    def f(self, b): return round(b * self.fpb)
    def note(self, v, name, b, dur, inst, off=None):
        n = name if isinstance(name, int) else m(name)
        self.v[v].append((self.f(b), n, inst))
        self.v[v].append((self.f(b + dur) if off is None else self.f(b) + off, 0, inst))
    def arp(self, v, names, b, dur, step=3):
        t0, t1, i = self.f(b), self.f(b + dur), 0
        t = t0
        while t < t1:
            self.v[v].append((t, m(names[i % len(names)]), ARP)); i += 1; t += step
        self.v[v].append((t1, 0, ARP))
    def stream(self, v):
        ev = sorted(self.v[v], key=lambda e: (e[0], e[1] != 0))  # at equal times gate-off first, then the new note
        ev.append((self.end, 0, 0))
        out = []
        for i, (t, n, inst) in enumerate(ev):
            nxt = ev[i + 1][0] if i + 1 < len(ev) else self.end + 1
            d = nxt - t
            out.append((min(d, 255), n, inst))
            d -= 255
            while d > 0:
                out.append((min(d, 255), 254, 0)); d -= 255
        out.append((0, 255, 0))
        # leading silence: shift the first event
        first = ev[0][0]
        if first > 0:
            lead = []
            d = first
            while d > 0: lead.append((min(d, 255), 254, 0)); d -= 255
            out = lead + out
        return out
# ---- win (jingleWin: 157 bpm, 20 beats)
W = Piece(157, 20)
W.note(0, 'G4', 1, 1, PIANO); W.note(0, 'A4', 2, 1, PIANO); W.note(0, 'F5', 3, 1, PIANO)
W.note(0, 'Eb5', 4, 4, BRASS); W.note(0, 'A4', 8, 1, STRINGS); W.note(0, 'G4', 9, 3, STRINGS)
W.note(0, 'D4', 13, 3, BRASS); W.note(0, 'E5', 16, 4, STRINGS)
W.note(1, 'Eb2', 4, 4, BASS); W.note(1, 'D2', 10, 2, BASS); W.note(1, 'G2', 13, 3, BASS); W.note(1, 'A1', 16, 4, BASS)
W.arp(2, ['Bb4', 'D5', 'F5'], 3, 1)
W.arp(2, ['Eb4', 'G4', 'Bb4', 'Eb5', 'Bb3'], 4, 4)
W.arp(2, ['D4', 'F4', 'A4', 'D5'], 10, 2)
W.arp(2, ['G3', 'B3', 'D4', 'G4'], 13, 3)
W.arp(2, ['C#4', 'E4', 'A4', 'C#5', 'E5'], 16, 4)
# ---- lose (jingleLose: 143 bpm, 16 beats)
L = Piece(143, 16)
L.note(0, 'A3', 0, 3.5, BRASS); L.note(0, 'D4', 4, 4, BRASS); L.note(0, 'F#5', 8, 2, STRINGS); L.note(0, 'A5', 10, 4, STRINGS); L.note(0, 'D4', 14, 2, STRINGS)
L.note(1, 'A2', 0, 3.5, BASS)
L.note(1, 'D2', 4, 8.12, BASS)
tp = 12
for b in (tp + 1/6, tp + 2/6, tp + .5, tp + .5 + 1/6, tp + .5 + 2/6, tp + 1, tp + 1 + 1/6, tp + 1 + 2/6, tp + 1.5):   # timpani roll on D3, pitch drops a fifth in 3 frames
    L.v[1].append((L.f(b), m('A3'), TIMP)); L.v[1].append((L.f(b) + 3, m('D3'), TIMP | 0x80))
L.note(1, 'D2', 13.75, 2.25, BASS)
for sb, db in ((2, .4), (3.5, .5)): L.note(2, 'A3', sb, db, STRINGS)
L.note(2, 'A2', 6, 2, STRINGS)
L.arp(2, ['D3', 'F#3', 'D5', 'F#5'], 10, 4, 4)
L.arp(2, ['D3', 'F#3', 'A3', 'D4'], 14, 2, 4)
print('/* jingle_gen.h - GENERATED by tools/gen_jingles.py. Do not edit. */\n#ifndef JINGLE_GEN_H\n#define JINGLE_GEN_H\n#include "types.h"')
print('/* instruments: SID control (waveform), pulse width high byte, attack/decay, sustain/release */')
for name, k in (('J_WAVE', 0), ('J_PW', 1), ('J_AD', 2), ('J_SR', 3)):
    print('static const u8 %s[%d] = { %s };' % (name, len(INST), ', '.join(str(i[k]) for i in INST)))
tot = 0
for tag, P in (('JW', W), ('JL', L)):
    for v in range(3):
        s = P.stream(v); tot += len(s) * 3
        print('static const u8 %s_V%d[%d] = {' % (tag, v, len(s) * 3))
        print('  ' + ', '.join('%d,%d,%d' % e for e in s))
        print('};')
    print('static const u8 *const %s_S[3] = { %s_V0, %s_V1, %s_V2 };' % (tag, tag, tag, tag))
print('#endif')
import sys
print('jingle data: %d bytes, win %d frames, lose %d frames' % (tot, W.end, L.end), file=sys.stderr)
