#!/usr/bin/env python3
"""Converts a Koala Painter file (10003 bytes) into a C header for src/loader.c: usage koa2h.py in.koa out.h"""
import sys
d = open(sys.argv[1], "rb").read()
if len(d) != 10003: sys.exit("%s: a Koala file must be exactly 10003 bytes (got %d)" % (sys.argv[1], len(d)))
d = d[2:]                                           # drop the load address
def arr(name, b):
    return "static const unsigned char %s[%d] = {\n%s\n};\n" % (name, len(b), ",".join(str(x) for x in b))
open(sys.argv[2], "w").write("/* generated by tools/koa2h.py - do not edit */\n" + arr("PIC_BMP", d[:8000]) + arr("PIC_SCR", d[8000:9000]) + arr("PIC_COL", d[9000:10000]) + "#define PIC_BG %d\n" % (d[10000] & 15))
