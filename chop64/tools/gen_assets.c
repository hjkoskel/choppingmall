/* gen_assets.c - host tool: runs the portable asset generator and writes src/assets_gen.h.
 * usage: gen_assets loading/win.koa > src/assets_gen.h        gen_assets --ppm > preview.ppm  (the finished picture as an image) */
#include <stdio.h>
#include <string.h>
#include "assets.h"
#include "core.h"
#include "mcfont.h"

static Assets A;
static void dump(const char *name, const u8 *d, int n, int per) {
  int i;
  printf("static const u8 %s[%d] = {\n", name, n);
  for (i = 0; i < n; i++) printf("%s%u,%s", (i % per == 0) ? "  " : "", d[i], (i % per == per - 1 || i == n - 1) ? "\n" : " ");
  printf("};\n");
}
/* Byte-RLE: control byte c < 0x80 = (c+1) literal bytes follow; c >= 0x80 = (c&0x7F)+3 copies of the next byte. Decoded on the C64 by unpack() in plat_c64.c. */
static int rle(const u8 *d, int n, u8 *out) {
  int i = 0, o = 0;
  while (i < n) {
    int run = 1, lit;
    while (i + run < n && d[i + run] == d[i] && run < 130) run++;
    if (run >= 3) { out[o++] = (u8)(0x80 | (run - 3)); out[o++] = d[i]; i += run; continue; }
    lit = 0;
    while (i + lit < n && lit < 128) { /* literals until the next run of 3+ */
      int j = i + lit;
      if (j + 2 < n && d[j] == d[j + 1] && d[j] == d[j + 2]) break;
      lit++;
    }
    out[o++] = (u8)(lit - 1); memcpy(out + o, d + i, (size_t)lit); o += lit; i += lit;
  }
  return o;
}
static void dump_z(const char *name, const u8 *bmp, const u8 *scr, const u8 *col) { /* three streams back to back: 8000 + 1000 + 1000 bytes */
  static u8 z[20000];
  int n = rle(bmp, 8000, z);
  n += rle(scr, 1000, z + n);
  n += rle(col, 1000, z + n);
  fprintf(stderr, "%s: %d bytes packed (from 10000)\n", name, n);
  dump(name, z, n, 16);
}
int main(int argc, char **argv) {
  static u8 font[GL_COUNT * 8];
  static unsigned char rgb[320 * 200 * 3];
  static u8 koa[10003];
  FILE *f;
  int i;
  game_init(1); /* fills the obstacle and door positions */
  assets_build(&A);
  if (argc > 1 && !strcmp(argv[1], "--ppm")) {
    picture_preview(&A, rgb);
    printf("P6\n320 200\n255\n");
    fwrite(rgb, 1, sizeof rgb, stdout);
    return 0;
  }
  for (i = 0; i < GL_COUNT; i++) picture_glyph_bytes((u8)i, font + i * 8);
  printf("/* assets_gen.h - GENERATED by tools/gen_assets.c (make assets). Do not edit. */\n#ifndef ASSETS_GEN_H\n#define ASSETS_GEN_H\n#include \"types.h\"\n");
  printf("/* multicolour bitmap picture of the mall (cell after cell), its colour matrix and colour RAM */\n");
  dump_z("ASSET_BG", A.bmp, A.scr, A.col);
  if (argc > 1 && (f = fopen(argv[1], "rb")) != NULL) { /* the victory picture (Koala format), shown when the player wins */
    if (fread(koa, 1, 10003, f) != 10003 || fgetc(f) != EOF) { fprintf(stderr, "%s must be a 10003-byte Koala file\n", argv[1]); return 1; }
    fclose(f);
    dump_z("ASSET_WIN", koa + 2, koa + 2 + 8000, koa + 2 + 9000);
    printf("#define WIN_BG %d\n", koa[2 + 10000] & 15);
  } else { fprintf(stderr, "no victory picture given: usage gen_assets loading/win.koa\n"); return 1; }
  dump("ASSET_SPR", A.spr, SH_COUNT * 64, 16);
  dump("ASSET_WALK", A.walk, 200 * 27, 27);
  dump("ASSET_MCFONT", font, GL_COUNT * 8, 8);
  printf("#endif\n");
  return 0;
}
